export function tipIndexForDate(dateKey: string, len: number): number {
  // simple stable rotation from date string
  let h = 0
  for (let i = 0; i < dateKey.length; i++) h = (h + dateKey.charCodeAt(i) * (i + 1)) % 997
  return len === 0 ? 0 : h % len
}
